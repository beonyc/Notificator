package com.example.notificator.service;

/** Итог исправления статуса дела за вчерашний день. */
public enum EditResult {
    /** Дело отмечено выполненным. */
    MARKED_DONE,
    /** Отметка о выполнении снята. */
    MARKED_UNDONE,
    /** Статус уже был таким, ничего не изменилось. */
    UNCHANGED,
    /** Отметка относится не ко вчерашнему дню: исправлять можно только вчера. */
    NOT_EDITABLE,
    /** Отметки нет или она принадлежит другому пользователю. */
    NOT_FOUND
}
