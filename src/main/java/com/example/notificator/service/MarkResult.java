package com.example.notificator.service;

/** Итог попытки отметить дело выполненным (нажатие кнопки «✅»). */
public enum MarkResult {
    /** Дело отмечено выполненным только что. */
    DONE,
    /** Дело уже было выполнено (например, кнопку нажали дважды). */
    ALREADY_DONE,
    /** Отметка относится к прошлому дню: отмечать можно только до 24:00 того же дня. */
    EXPIRED,
    /** Отметки нет или она принадлежит другому пользователю. */
    NOT_FOUND
}
